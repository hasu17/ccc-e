                    The foundation of Consortium for Climate Change – Ethiopia (CCC-E) is strongly related with the Ethiopian Civil Society Network on Climate Change (ECSNCC). 
                <p>
                   ECSNCC was established in 2007 with founding members including Dan Church Aid, Forum for Environment, Sustainable Land Use Forum, SOS Sahel, Poverty Action Network Ethiopia (PANE), and Action for Development (AfD). The network was officially launched in 2009 with FfE acting as the secretariat and host. However, ECSNCC faced challenges that hindered its continued operation, and in 2013, FfE initiated discussions with the Steering Committee to revitalize the network. The General Assembly meeting took place in November 2013, during which it was unanimously agreed to kick-start the registration process of ECSNCC as a network of individual CSOs, withdraw four member Consortia while continuing to collaborate, allow FfE to continue hosting the network, designate the aforementioned four consortia to serve as a Technical Advisory Group of the new Steering Committee of ECSNCC, revive and strengthen regional and international partnerships and participation, and establish a new Steering Committee.
                </p>
                <p>
                    After extensive efforts, the network was successfully registered as the Consortium for Climate Change-Ethiopia (CCC-E), a coalition of Ethiopian Residents and Foreign Charity Organizations. 
</p> 
<p>
    This transformation from ECSNCC to CCC-E was a prolonged and demanding process that required significant collaboration from key partners such as FfE, DCA, the Pan African Climate Justice Alliance (PACJA), and TKA. Their unwavering commitment enabled CCC-E to overcome obstacles and serve the community effectively. Their contributions have had a lasting impact on both CCC-E and the community it serves. Currently, CCC-E is registered as a local consortium of CSOs. It was in December 2014, that CCC-E was legally registered with the support of ENDA, LEM Ethiopia, and ISD. Their knowledge, experience, and commitment have helped CCC-E to legally register with the Federal Charities and Societies Agency as an Ethiopian Resident and Foreign Charity Consortium. Moreover, ENDA, LEM Ethiopia, and ISD supported CCC-E in developing the strategic and operational plans of CCC-E, ensuring its alignment with national and international climate change policies and objectives. This is a testament to the contribution of ENDA, LEM Ethiopia, and ISD in the process of CCC-E establishment and registration.
